function retireMigration(e, n) {
  const legacy = `legacy_${e.table}`;
  return src(
    `// Copies what is still only in ${legacy}, checks that everything arrived, and only then drops the old table.`,
    'export async function up(db) {',
    `  const legacy = await db.table('${legacy}').all();`,
    `  const kept = new Set((await db.table('${e.table}').all()).map((row) => row.id));`,
    '  for (const row of legacy) {',
    `    if (!kept.has(row.id)) await db.table('${e.table}').put({ ...row, migration: ${n} });`,
    '  }',
    `  const moved = new Set((await db.table('${e.table}').all()).map((row) => row.id));`,
    '  const missing = legacy.filter((row) => !moved.has(row.id));',
    `  if (missing.length) throw new Error(\`\${missing.length} rows did not copy, so ${legacy} stays\`);`,
    `  await db.dropTable('${legacy}');`,
    '}',
  );
}

